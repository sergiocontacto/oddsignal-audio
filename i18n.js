// Las paginas con mucho texto propio traen sus cadenas en un archivo
// aparte y se fusionan aqui, para no cargar todo ese texto en el resto
// de paginas que no lo necesitan.
if (window.EXTRA_TRANSLATIONS) {
    for (const lang in window.EXTRA_TRANSLATIONS) {
        if (!translations[lang]) translations[lang] = {};
        Object.assign(translations[lang], window.EXTRA_TRANSLATIONS[lang]);
    }
}

// Sin eleccion guardada se usa el idioma del navegador si esta traducido.
const browserLang = (navigator.language || 'en').slice(0, 2);
let currentLang = localStorage.getItem('selectedLang') || (translations[browserLang] ? browserLang : 'en');

function translatePage() {
    document.documentElement.lang = currentLang;
    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        null,
        false
    );

    let node;
    while (node = walker.nextNode()) {
        const text = node.textContent.trim();
        if (text && translations[currentLang][text]) {
            node.textContent = translations[currentLang][text];
        }
    }

    const selector = document.getElementById('language-selector');
    if (selector) selector.value = currentLang;
}

document.addEventListener('DOMContentLoaded', function() {
    translatePage();

    const selector = document.getElementById('language-selector');
    if (selector) {
        selector.addEventListener('change', function(e) {
            currentLang = e.target.value;
            localStorage.setItem('selectedLang', currentLang);
            location.reload();
        });
    }
});
